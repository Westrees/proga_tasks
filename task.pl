слева_от(X, Y) :- 
    место(X), место(Y),
    (X =:= Y - 1 ; (X =:= 4, Y =:= 1)).
справа_от(X, Y) :- 
    слева_от(Y, X).
напротив(X, Y) :-
    место(X), место(Y),
    ( (X =:= 1, Y =:= 3) ; (X =:= 3, Y =:= 1) ;
      (X =:= 2, Y =:= 4) ; (X =:= 4, Y =:= 2) ).
решение(Волк_место, Ниф_место, Наф_место, Нуф_место, 
        Волк_тема, Ниф_тема, Наф_тема, Нуф_тема) :-
    permutation([1, 2, 3, 4], [Волк_место, Ниф_место, Наф_место, Нуф_место]),
    permutation([флора, спорт, космос, фауна], 
                [Волк_тема, Ниф_тема, Наф_тема, Нуф_тема]),
    Волк_тема = фауна,
    слева_от(Волк_место, Наф_место),
    напротив(Нуф_место, Наф_место),
    Нуф_тема \= спорт,
    ((Ниф_тема = космос, Космос_место = Ниф_место);(Наф_тема = космос, Космос_место = Наф_место) ;
    (Нуф_тема = космос, Космос_место = Нуф_место);(Волк_тема = космос, Космос_место = Волк_место)),
    справа_от(Ниф_место, Космос_место).
